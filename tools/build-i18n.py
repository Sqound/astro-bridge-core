"""Compile reviewed catalogs into one flat public asset, without runtime fetching."""
import argparse
from collections import Counter
import json
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parents[1]
LOCALES=[('en','English','EN'),('fr','Français','FR'),('ja','日本語','JA'),('de','Deutsch','DE'),
         ('es','Español','ES'),('it','Italiano','IT'),('pt-BR','Português (Brasil)','PT'),
         ('zh-Hans','简体中文','简'),('zh-Hant','繁體中文','繁'),('ru','Русский','RU')]

def compile_catalogs():
    catalogs={tag:json.loads((ROOT/'locales'/f'{tag}.json').read_text()) for tag,_,_ in LOCALES}
    keys=set(catalogs['en']);complete={}
    placeholders=lambda value:sorted(re.findall(r'\{([a-zA-Z][a-zA-Z0-9_]*)\}',value))
    for tag,values in catalogs.items():
        complete[tag]=set(values)==keys
        if set(values)-keys:raise ValueError(f'{tag}: unknown keys')
        for key,value in values.items():
            if not isinstance(value,str) or not value.strip():raise ValueError(f'{tag}: empty translation: {key}')
            if placeholders(value)!=placeholders(catalogs['en'][key]):raise ValueError(f'{tag}: placeholders: {key}')
            literals=re.findall(r'https?://[A-Za-z0-9./:_-]+|(?:[0-9]{1,3}\.){3}[0-9]{1,3}|\.local\b|/api/v[0-9]+(?:/[A-Za-z0-9_-]+)*|/interfaces\b',key)
            if any(literal not in value for literal in literals):raise ValueError(f'{tag}: changed address or API literal: {key}')
            numbers=lambda text:Counter(re.findall(r'\d+(?:\.\d+)*',text))
            if numbers(catalogs['en'][key])-numbers(value):raise ValueError(f'{tag}: missing operational number: {key}')
    languages=[dict(tag=tag,name=name,short=short,complete=complete[tag]) for tag,name,short in LOCALES]
    return ('/* Generated by tools/build-i18n.py; edit locales/*.json and tools/i18n/runtime.js. */\n'
        '(() => {\n  "use strict";\n  const locales = '+json.dumps(languages,ensure_ascii=False,indent=2)+';\n'
        '  const catalogs = '+json.dumps(catalogs,ensure_ascii=False,indent=2)+';\n'
        +(ROOT/'tools/i18n/runtime.js').read_text())

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    path=ROOT/'wifi_bridge/static/i18n.js';value=compile_catalogs()
    if args.check:
        if path.read_text()!=value:raise SystemExit('Catalog asset is stale; run python3 tools/build-i18n.py')
    else:path.write_text(value)
